  STAGE4_2R3C3T13S24D1R14R8R4_COMMAND="${STAGE4_2R3C3T13S24D1R14R8R4_COMMAND}" \
  STAGE4_2R3C3T13S24D1R14R8R4_RESUME="${STAGE4_2R3C3T13S24D1R14R8R4_RESUME}" \
