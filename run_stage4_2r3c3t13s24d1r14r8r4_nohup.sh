  STAGE4_2R3C3T13S24D1R14R8R4_R8_RUN="${STAGE4_2R3C3T13S24D1R14R8R4_R8_RUN}" \
  STAGE4_2R3C3T13S24D1R14R8R4_R8R2_OUTPUT="${STAGE4_2R3C3T13S24D1R14R8R4_R8R2_OUTPUT}" \
  STAGE4_2R3C3T13S24D1R14R8R4_R8R3_OUTPUT="${STAGE4_2R3C3T13S24D1R14R8R4_R8R3_OUTPUT}" \
  RAY_TMPDIR="${RAY_TMPDIR}" \
  bash "${PROJECT_DIR}/run_stage4_2r3c3t13s24d1r14r8r4_native.sh" >"${LOG_FILE}" 2>&1 < /dev/null &
