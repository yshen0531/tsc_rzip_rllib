#!/usr/bin/env bash
set -euo pipefail
PROJECT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
source "${PROJECT_DIR}/scripts/stage4_2r3c3t13s24d1r14r8r1_shell_common.sh"
stage4_2r3c3t13s24d1r14r8r1_validate
mkdir -p "${PROJECT_DIR}/logs/nohup" "${STAGE4_2R3C3T13S24D1R14R8R1_OUTPUT_ROOT}"
if [[ -z "${STAGE4_2R3C3T13S24D1R14R8R1_OUTPUT_DIR:-}" ]]; then
  STAGE4_2R3C3T13S24D1R14R8R1_OUTPUT_DIR="$(stage4_2r3c3t13s24d1r14r8r1_new_output)"
  export STAGE4_2R3C3T13S24D1R14R8R1_OUTPUT_DIR
fi
STAMP="$(date -u +%Y%m%d_%H%M%S)"
LOG_FILE="${STAGE4_2R3C3T13S24D1R14R8R1_LOG_FILE:-${PROJECT_DIR}/logs/nohup/stage4_2r3c3t13s24d1r14r8r1_${STAGE4_2R3C3T13S24D1R14R8R1_COMMAND}_${STAMP}.log}"
PID_FILE="${STAGE4_2R3C3T13S24D1R14R8R1_OUTPUT_ROOT}/stage4_2r3c3t13s24d1r14r8r1.pid"
nohup env \
  STAGE4_2R3C3T13S24D1R14R8R1_PROJECT_DIR="${STAGE4_2R3C3T13S24D1R14R8R1_PROJECT_DIR}" \
  STAGE4_2R3C3T13S24D1R14R8R1_CONFIG="${STAGE4_2R3C3T13S24D1R14R8R1_CONFIG}" \
  STAGE4_2R3C3T13S24D1R14R8R1_PYTHON="${STAGE4_2R3C3T13S24D1R14R8R1_PYTHON}" \
  STAGE4_2R3C3T13S24D1R14R8R1_COMMAND="${STAGE4_2R3C3T13S24D1R14R8R1_COMMAND}" \
  STAGE4_2R3C3T13S24D1R14R8R1_OUTPUT_DIR="${STAGE4_2R3C3T13S24D1R14R8R1_OUTPUT_DIR}" \
  bash "${PROJECT_DIR}/run_stage4_2r3c3t13s24d1r14r8r1_native.sh" >"${LOG_FILE}" 2>&1 < /dev/null &
PID=$!
printf '%s\n' "${PID}" > "${PID_FILE}"
printf '[R8R1] pid=%s\n[R8R1] output=%s\n[R8R1] log=%s\n' "${PID}" "${STAGE4_2R3C3T13S24D1R14R8R1_OUTPUT_DIR}" "${LOG_FILE}"
