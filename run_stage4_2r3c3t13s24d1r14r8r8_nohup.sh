  STAGE4_2R3C3T13S24D1R14R8R8_RUN_DIR="${STAGE4_2R3C3T13S24D1R14R8R8_RUN_DIR}" \
  STAGE4_2R3C3T13S24D1R14R8R8_R8R7_RUN="${STAGE4_2R3C3T13S24D1R14R8R8_R8R7_RUN}" \
  bash "${PROJECT_DIR}/run_stage4_2r3c3t13s24d1r14r8r8_native.sh" >"${LOG_FILE}" 2>&1 < /dev/null &
