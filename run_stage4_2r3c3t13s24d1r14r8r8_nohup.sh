  STAGE4_2R3C3T13S24D1R14R8R8_PROJECT_DIR="${STAGE4_2R3C3T13S24D1R14R8R8_PROJECT_DIR}" \
  STAGE4_2R3C3T13S24D1R14R8R8_CONFIG="${STAGE4_2R3C3T13S24D1R14R8R8_CONFIG}" \
  STAGE4_2R3C3T13S24D1R14R8R8_PYTHON="${STAGE4_2R3C3T13S24D1R14R8R8_PYTHON}" \
  STAGE4_2R3C3T13S24D1R14R8R8_COMMAND="${STAGE4_2R3C3T13S24D1R14R8R8_COMMAND}" \
