  STAGE4_2R3C3T13S24D1R14R8R8_RUN_DIR="$(stage4_2r3c3t13s24d1r14r8r8_new_run_dir)"
  export STAGE4_2R3C3T13S24D1R14R8R8_RUN_DIR
