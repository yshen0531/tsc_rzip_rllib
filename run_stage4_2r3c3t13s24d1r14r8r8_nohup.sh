printf '%s\n' "${PID}" > "${PID_FILE}"
printf '[R8R8] pid=%s\n[R8R8] run_dir=%s\n[R8R8] log=%s\n' "${PID}" "${STAGE4_2R3C3T13S24D1R14R8R8_RUN_DIR}" "${LOG_FILE}"
