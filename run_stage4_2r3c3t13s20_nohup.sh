#!/usr/bin/env bash
set -euo pipefail
PROJECT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
source "${PROJECT_DIR}/scripts/stage4_2r3c3t13s20_shell_common.sh"
stage4_2r3c3t13s20_validate_common
mkdir -p "${PROJECT_DIR}/logs/nohup" "${STAGE4_2R3C3T13S20_OUTPUT_ROOT}"
if [[ -z "${STAGE4_2R3C3T13S20_RUN_DIR:-}" ]]; then
  STAGE4_2R3C3T13S20_RUN_DIR="$(stage4_2r3c3t13s20_new_run_dir)"
  export STAGE4_2R3C3T13S20_RUN_DIR
fi
STAMP="$(date -u +%Y%m%d_%H%M%S)"
LOG_FILE="${STAGE4_2R3C3T13S20_LOG_FILE:-${PROJECT_DIR}/logs/nohup/stage4_2r3c3t13s20_${STAGE4_2R3C3T13S20_COMMAND}_${STAMP}.log}"
PID_FILE="${STAGE4_2R3C3T13S20_OUTPUT_ROOT}/stage4_2r3c3t13s20_driver.pid"
printf '%s\n' "${STAGE4_2R3C3T13S20_RUN_DIR}" > "${STAGE4_2R3C3T13S20_OUTPUT_ROOT}/latest_stage4_2r3c3t13s20_run.txt"
printf '%s\n' "${LOG_FILE}" > "${PROJECT_DIR}/logs/nohup/latest_stage4_2r3c3t13s20.log"
nohup env \
  STAGE4_2R3C3T13S20_PROJECT_DIR="${STAGE4_2R3C3T13S20_PROJECT_DIR}" \
  STAGE4_2R3C3T13S20_CONFIG="${STAGE4_2R3C3T13S20_CONFIG}" \
  STAGE4_2R3C3T13S20_PYTHON="${STAGE4_2R3C3T13S20_PYTHON}" \
  STAGE4_2R3C3T13S20_WORKERS="${STAGE4_2R3C3T13S20_WORKERS}" \
  STAGE4_2R3C3T13S20_BACKEND="${STAGE4_2R3C3T13S20_BACKEND}" \
  STAGE4_2R3C3T13S20_COMMAND="${STAGE4_2R3C3T13S20_COMMAND}" \
  STAGE4_2R3C3T13S20_RESUME="${STAGE4_2R3C3T13S20_RESUME}" \
  STAGE4_2R3C3T13S20_RUN_DIR="${STAGE4_2R3C3T13S20_RUN_DIR}" \
  STAGE4_2R3C3T13S20_TSC_WORKSPACE_ROOT="${STAGE4_2R3C3T13S20_TSC_WORKSPACE_ROOT}" \
  STAGE4_2R3C3T13S20_TSC_RUN_ROOT="${STAGE4_2R3C3T13S20_TSC_RUN_ROOT}" \
  RAY_TMPDIR="${RAY_TMPDIR}" \
  bash "${PROJECT_DIR}/run_stage4_2r3c3t13s20_native.sh" >"${LOG_FILE}" 2>&1 < /dev/null &
PID=$!
printf '%s\n' "${PID}" > "${PID_FILE}"
printf '[T13S20] pid=%s\n[T13S20] run_dir=%s\n[T13S20] log=%s\n' "${PID}" "${STAGE4_2R3C3T13S20_RUN_DIR}" "${LOG_FILE}"
