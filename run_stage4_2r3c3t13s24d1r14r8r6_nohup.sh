nohup env \
  STAGE4_2R3C3T13S24D1R14R8R6_PROJECT_DIR="${STAGE4_2R3C3T13S24D1R14R8R6_PROJECT_DIR}" \
  STAGE4_2R3C3T13S24D1R14R8R6_CONFIG="${STAGE4_2R3C3T13S24D1R14R8R6_CONFIG}" \
  STAGE4_2R3C3T13S24D1R14R8R6_PYTHON="${STAGE4_2R3C3T13S24D1R14R8R6_PYTHON}" \
  STAGE4_2R3C3T13S24D1R14R8R6_COMMAND="${STAGE4_2R3C3T13S24D1R14R8R6_COMMAND}" \
  STAGE4_2R3C3T13S24D1R14R8R6_RUN_DIR="${STAGE4_2R3C3T13S24D1R14R8R6_RUN_DIR}" \
  STAGE4_2R3C3T13S24D1R14R8R6_R8R5_RUN="${STAGE4_2R3C3T13S24D1R14R8R6_R8R5_RUN}" \
  bash "${PROJECT_DIR}/run_stage4_2r3c3t13s24d1r14r8r6_native.sh" >"${LOG_FILE}" 2>&1 < /dev/null &
PID=$!
printf '%s\n' "${PID}" > "${PID_FILE}"
printf '[R8R6] pid=%s\n[R8R6] run_dir=%s\n[R8R6] log=%s\n' "${PID}" "${STAGE4_2R3C3T13S24D1R14R8R6_RUN_DIR}" "${LOG_FILE}"
