#!/usr/bin/env bash
set -euo pipefail
PROJECT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
source "${PROJECT_DIR}/scripts/stage4_2r3c3t13s24d1r14r8r6_shell_common.sh"
stage4_2r3c3t13s24d1r14r8r6_validate
mkdir -p "${PROJECT_DIR}/logs/nohup" "${STAGE4_2R3C3T13S24D1R14R8R6_OUTPUT_ROOT}"
if [[ -z "${STAGE4_2R3C3T13S24D1R14R8R6_RUN_DIR:-}" ]]; then
  STAGE4_2R3C3T13S24D1R14R8R6_RUN_DIR="$(stage4_2r3c3t13s24d1r14r8r6_new_run_dir)"
  export STAGE4_2R3C3T13S24D1R14R8R6_RUN_DIR
fi
STAMP="$(date -u +%Y%m%d_%H%M%S)"
LOG_FILE="${STAGE4_2R3C3T13S24D1R14R8R6_LOG_FILE:-${PROJECT_DIR}/logs/nohup/stage4_2r3c3t13s24d1r14r8r6_${STAGE4_2R3C3T13S24D1R14R8R6_COMMAND}_${STAMP}.log}"
